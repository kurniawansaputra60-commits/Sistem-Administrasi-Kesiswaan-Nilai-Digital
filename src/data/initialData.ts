export function generateGrades(offset: number = 0): SubjectGrade[] {
  return defaultSubjects.map((sub, i) => {
    const base = 78 + ((i * 3 + offset) % 18);
    const tugas = Math.min(98, base + (i % 4));
    const uts = Math.min(96, base - 2 + (i % 3));
    const uas = Math.min(97, base + 1 + (i % 5));
    const nilaiAkhir = Math.round((tugas * 0.3 + uts * 0.3 + uas * 0.4) * 10) / 10;
    let predikat: 'A' | 'B' | 'C' | 'D' = 'B';
    if (nilaiAkhir >= 88) predikat = 'A';
    else if (nilaiAkhir >= 78) predikat = 'B';
    else if (nilaiAkhir >= 70) predikat = 'C';
    else predikat = 'D';

    return {
      subjectId: sub.subjectId,
      subjectName: sub.subjectName,
      kkm: sub.kkm,
      tugas,
      uts,
      uas,
      nilaiAkhir,
      predikat,
    };
  });
}

